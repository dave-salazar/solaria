-- ---------- 1. Tables -------------------------------------------------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  sku         text,
  name        text not null check (char_length(name) between 1 and 80),
  inspired_by text,                                   -- shown as "Inspired by <original>"
  family      text default 'Woody',                   -- scent family
  shop_for    text default 'Unisex' check (shop_for in ('Men','Women','Unisex')),
  concentration text default 'Eau de Parfum',
  top_notes   text,
  heart_notes text,
  base_notes  text,
  description text,
  image_url   text,
  is_featured boolean not null default false,
  is_new      boolean not null default false,
  status      text not null default 'active' check (status in ('active','hidden')),
  added_at    timestamptz not null default now()
);

-- One row per bottle size. Each size has its own price and stock.
create table if not exists public.product_variants (
  id         bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  ml         integer not null check (ml between 1 and 500),
  price      numeric not null check (price >= 0),
  stock      integer not null default 0 check (stock >= 0),
  unique (product_id, ml)
);
create index if not exists variants_product_idx on public.product_variants (product_id);

create table if not exists public.orders (
  id             text primary key,
  user_id        uuid references auth.users(id) on delete set null,
  payment        text not null default 'cod',
  shipping       numeric not null default 0,
  discount       numeric not null default 0,
  total          numeric not null default 0,
  status         text not null default 'pending',
  customer_name  text,
  customer_phone text,
  customer_email text,
  address_line   text,
  city           text,
  province       text,
  postal_code    text,
  created_at     timestamptz not null default now()
);
create index if not exists orders_user_idx on public.orders (user_id, created_at desc);

create table if not exists public.order_items (
  id          bigint generated by default as identity primary key,
  order_id    text not null references public.orders(id) on delete cascade,
  product_id  text,
  variant_id  bigint,
  name        text,
  inspired_by text,
  ml          integer,
  qty         integer,
  price       numeric
);
create index if not exists order_items_order_idx on public.order_items (order_id);

create table if not exists public.admins (
  email   text,
  user_id uuid
);

create table if not exists public.addresses (
  id           uuid primary key default gen_random_uuid(),
  user_id      uuid not null references auth.users(id) on delete cascade,
  label        text,
  full_name    text not null,
  phone        text not null,
  address_line text not null,
  city         text not null,
  province     text not null,
  postal_code  text,
  is_default   boolean not null default false,
  created_at   timestamptz not null default now()
);

create table if not exists public.reviews (
  id          uuid primary key default gen_random_uuid(),
  product_id  text not null,
  user_id     uuid not null references auth.users(id) on delete cascade,
  rating      integer not null check (rating between 1 and 5),
  comment     text not null check (char_length(comment) between 3 and 1000),
  public_name text,
  created_at  timestamptz not null default now(),
  unique (product_id, user_id)
);

create table if not exists public.stock_alerts (
  id         uuid primary key default gen_random_uuid(),
  product_id text not null,
  user_id    uuid not null references auth.users(id) on delete cascade,
  email      text,
  created_at timestamptz not null default now(),
  unique (product_id, user_id)
);

create table if not exists public.contact_messages (
  id         uuid primary key default gen_random_uuid(),
  name       text not null check (char_length(name) between 1 and 80),
  email      text not null check (char_length(email) between 5 and 120),
  message    text not null check (char_length(message) between 5 and 2000),
  created_at timestamptz not null default now()
);

create or replace view public.product_ratings as
  select product_id, round(avg(rating)::numeric, 1) as avg_rating, count(*)::int as review_count
  from public.reviews group by product_id;

-- ---------- 2. Functions ----------------------------------------------
-- Admin = a row in public.admins matching the signed-in user (by id, or by CONFIRMED email).
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.admins a join auth.users u on u.id = auth.uid()
    where a.user_id = u.id
       or (a.user_id is null and u.email_confirmed_at is not null and lower(a.email) = lower(u.email))
  );
$$;

drop function if exists public.place_order(jsonb, text, jsonb);
drop function if exists public.cancel_order(text);

-- Shipping: PHP 150, free from PHP 2,500.  Welcome voucher: PHP 100 off the first order.
-- (keep in sync with SOLRules in cart.js)
create function public.place_order(p_items jsonb, p_payment text, p_customer jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_admin boolean := public.is_admin();
  v_pay text := lower(coalesce(p_payment, 'cod'));
  v_name text  := left(nullif(trim(p_customer ->> 'name'), ''), 80);
  v_phone text := left(nullif(trim(p_customer ->> 'phone'), ''), 20);
  v_addr text  := left(nullif(trim(p_customer ->> 'address_line'), ''), 200);
  v_city text  := left(nullif(trim(p_customer ->> 'city'), ''), 80);
  v_prov text  := left(nullif(trim(p_customer ->> 'province'), ''), 80);
  v_zip text   := left(nullif(trim(p_customer ->> 'postal_code'), ''), 10);
  it jsonb; v rec; v_qty int;
  v_sub numeric := 0; v_ship numeric; v_disc numeric := 0; v_total numeric; v_id text;
begin
  if v_uid is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then
    raise exception 'EMPTY_ORDER';
  end if;
  if v_pay not in ('cod', 'gcash', 'maya') then raise exception 'BAD_PAYMENT'; end if;
  -- Online payments are not live yet: customers can only use cash on delivery.
  if not v_admin and v_pay <> 'cod' then raise exception 'PAYMENT_UNAVAILABLE'; end if;
  if not v_admin then
    if v_name is null or v_phone is null or v_addr is null or v_city is null or v_prov is null then
      raise exception 'ADDRESS_REQUIRED';
    end if;
    if v_phone !~ '^[0-9+() -]{7,20}$' then raise exception 'BAD_PHONE'; end if;
    if (select count(*) from public.orders where user_id = v_uid and status = 'pending') >= 5 then
      raise exception 'TOO_MANY_PENDING';
    end if;
  end if;

  loop
    v_id := 'SOL-' || lpad((floor(random() * 900000) + 100000)::int::text, 6, '0');
    exit when not exists (select 1 from public.orders where id = v_id);
  end loop;

  insert into public.orders (id, payment, shipping, discount, total, customer_name, customer_phone,
                             customer_email, address_line, city, province, postal_code, user_id)
  values (v_id, v_pay, 0, 0, 0, coalesce(v_name, 'Guest'), v_phone,
          case when v_admin then null else auth.jwt() ->> 'email' end,
          v_addr, v_city, v_prov, v_zip, case when v_admin then null else v_uid end);

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := greatest(1, least(10, coalesce((it ->> 'qty')::int, 1)));
    update public.product_variants pv set stock = pv.stock - v_qty
     where pv.id = (it ->> 'variant_id')::bigint and pv.stock >= v_qty
       and exists (select 1 from public.products p where p.id = pv.product_id and p.status = 'active')
    returning pv.id, pv.product_id, pv.ml, pv.price into v;
    if not found then raise exception 'OUT_OF_STOCK:%', coalesce(it ->> 'n', it ->> 'variant_id'); end if;
    insert into public.order_items (order_id, product_id, variant_id, name, inspired_by, ml, qty, price)
    select v_id, p.id::text, v.id, p.name, p.inspired_by, v.ml, v_qty, v.price
      from public.products p where p.id = v.product_id;
    v_sub := v_sub + v.price * v_qty;
  end loop;

  v_ship := case when v_sub >= 2500 then 0 else 150 end;
  if not v_admin and not exists (
       select 1 from public.orders where user_id = v_uid and status <> 'cancelled' and id <> v_id) then
    v_disc := least(100, v_sub);
  end if;
  v_total := greatest(0, v_sub + v_ship - v_disc);
  update public.orders set shipping = v_ship, discount = v_disc, total = v_total where id = v_id;
  return jsonb_build_object('id', v_id, 'subtotal', v_sub, 'shipping', v_ship, 'discount', v_disc, 'total', v_total);
end $$;

-- A customer can cancel their own order while it is 'pending'; stock goes back.
create function public.cancel_order(p_id text) returns void
language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype;
begin
  select * into o from public.orders where id = p_id and user_id = auth.uid() for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if o.status <> 'pending' then raise exception 'NOT_CANCELLABLE'; end if;
  update public.product_variants v set stock = v.stock + i.qty
    from public.order_items i where i.order_id = p_id and i.variant_id = v.id;
  update public.orders set status = 'cancelled' where id = p_id;
end $$;

-- Admin-only status changes (restocks on cancel, re-reserves on un-cancel).
create or replace function public.set_order_status(p_id text, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare o public.orders%rowtype;
begin
  if not public.is_admin() then raise exception 'FORBIDDEN'; end if;
  if p_status not in ('pending','paid','shipped','delivered','cancelled') then raise exception 'BAD_STATUS'; end if;
  select * into o from public.orders where id = p_id for update;
  if not found then raise exception 'NOT_FOUND'; end if;
  if o.status <> 'cancelled' and p_status = 'cancelled' then
    update public.product_variants v set stock = v.stock + i.qty
      from public.order_items i where i.order_id = p_id and i.variant_id = v.id;
  elsif o.status = 'cancelled' and p_status <> 'cancelled' then
    if exists (select 1 from public.order_items i join public.product_variants v on v.id = i.variant_id
               where i.order_id = p_id and v.stock < i.qty) then
      raise exception 'OUT_OF_STOCK';
    end if;
    update public.product_variants v set stock = v.stock - i.qty
      from public.order_items i where i.order_id = p_id and i.variant_id = v.id;
  end if;
  update public.orders set status = p_status where id = p_id;
end $$;

-- Only customers with a DELIVERED order containing the perfume can review it (one review each, editable).
create or replace function public.submit_review(p_product_id text, p_rating int, p_comment text, p_public_name text)
returns void language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'LOGIN_REQUIRED'; end if;
  if p_rating is null or p_rating not between 1 and 5 then raise exception 'BAD_RATING'; end if;
  if p_comment is null or char_length(trim(p_comment)) not between 3 and 1000 then raise exception 'BAD_COMMENT'; end if;
  if not exists (select 1 from public.orders o join public.order_items i on i.order_id = o.id
                 where o.user_id = v_uid and o.status = 'delivered' and i.product_id = p_product_id) then
    raise exception 'NOT_VERIFIED_BUYER';
  end if;
  insert into public.reviews (product_id, user_id, rating, comment, public_name)
  values (p_product_id, v_uid, p_rating, trim(p_comment), left(nullif(trim(p_public_name), ''), 40))
  on conflict (product_id, user_id)
  do update set rating = excluded.rating, comment = excluded.comment,
                public_name = excluded.public_name, created_at = now();
end $$;

